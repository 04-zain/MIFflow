"""Keep primary reference labels, generated boundaries and model outputs aligned."""

from collections.abc import Mapping
from typing import Literal

from mif_pipeline.pipeline_core.config import PrimaryClassifierSettings

from ._shared import BatchTrainingError, ClassifierKind


def primary_ignore_policy(
    settings: PrimaryClassifierSettings,
    model_configuration: Mapping[str, object],
) -> Literal["none", "annotated", "boundary"]:
    """Validate the explicit source of the optional primary Ignore output.

    Annotated Ignore uses saved reference regions as an ordinary learned class.
    Boundary Ignore is generated by QuPath's boundary strategy and has no
    reference annotations. We keep these choices distinct when checking the
    selected estimator, including an estimator wrapped by KRONOS or tuning.
    """
    # Import at the operation boundary: native projections also depend on plans.
    from .engines import _parse_native_model_configuration
    from .cross_validation import native_estimator_configuration

    if type(settings) is not PrimaryClassifierSettings:
        raise BatchTrainingError("primary Ignore policy requires complete settings")
    configuration = native_estimator_configuration(_parse_native_model_configuration(
        model_configuration, ClassifierKind.PRIMARY_COMPARTMENT,
    ))
    biological = {item.class_id for item in settings.primary_classes}
    declared = tuple(settings.primary_classifier.output_classes)
    labels = configuration.output_labels.ordered_labels
    outputs = tuple(item.canonical_class_id for item in labels)
    if outputs != declared:
        raise BatchTrainingError("primary model labels differ from the selected output inventory")
    annotated = settings.primary_classifier.require_ignore_training
    if configuration.boundary_strategy == "classify":
        if annotated:
            raise BatchTrainingError("annotated Ignore and generated boundary Ignore are separate choices")
        boundary = tuple(item for item in labels
                         if item.qupath_label == configuration.boundary_class_id)
        if (len(boundary) != 1 or boundary[0].canonical_class_id != "Ignore"
                or set(outputs) != biological | {"Ignore"}):
            raise BatchTrainingError("primary boundary classification requires one generated Ignore output")
        return "boundary"
    expected = biological | {"Ignore"} if annotated else biological
    if set(outputs) != expected:
        raise BatchTrainingError("primary skipped boundaries require only the selected reference classes")
    return "annotated" if annotated else "none"


def primary_training_required_classes(
    settings: PrimaryClassifierSettings,
    model_configuration: Mapping[str, object] | None = None,
) -> tuple[str, ...]:
    """Return the classes that need actual saved training annotations.

    We include Ignore only when its annotations were explicitly requested.
    New plan production also supplies the model configuration to check that
    its output and boundary choices agree. Retained plans remain readable for
    a public settings amendment before fitting.
    """
    if type(settings) is not PrimaryClassifierSettings:
        raise BatchTrainingError("primary reference classes require complete settings")
    if model_configuration is not None:
        primary_ignore_policy(settings, model_configuration)
    required = [item.class_id for item in settings.primary_classes]
    if settings.primary_classifier.require_ignore_training:
        required.append("Ignore")
    return tuple(sorted(required))
